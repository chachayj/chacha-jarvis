CREATE TABLE IF NOT EXISTS administrative.administrative_districts (
  -- 기본 키: (province_code, district_code)
  province_code              text            NOT NULL,
  province_name              text            NOT NULL,
  country_code               char(2)         NOT NULL,
  district_code              text            NOT NULL,  -- 예: junggu, seochogu

  -- OSM 원본 필드 + 지오메트리
  geom                       geometry(MultiPolygon, 4326),
  osm_id                     bigint,
  name                       text,
  name_en                    text,
  boundary                   text,
  admin_level                integer,
  admin_centre_node_id       bigint,
  admin_centre_node_lat      double precision,
  admin_centre_node_lng      double precision,
  label_node_id              bigint,
  label_node_lat             double precision,
  label_node_lng             double precision,

  CONSTRAINT administrative_districts_pk PRIMARY KEY (province_code, district_code)
);



-- 공간/조회 인덱스
CREATE INDEX IF NOT EXISTS administrative_districts_gix
  ON administrative.administrative_districts USING GIST (geom);
CREATE INDEX IF NOT EXISTS administrative_districts_province_idx
  ON administrative.administrative_districts (province_code);
CREATE INDEX IF NOT EXISTS administrative_districts_osm_id_idx
  ON administrative.administrative_districts (osm_id);


