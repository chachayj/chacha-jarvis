  IS '레이블 기준 경도(WGS84).';





  
  
  
CREATE TABLE administrative.administrative_boundary_centers_by_province (
	province_code text NOT NULL,
	osm_id int8 NOT NULL,
	longitude float8 NOT NULL,
	latitude float8 NOT NULL,
	created_at timestamptz DEFAULT now() NULL,
	district_code text NULL,
	CONSTRAINT administrative_boundary_centers_by_province_pkey PRIMARY KEY (province_code, osm_id),
	CONSTRAINT administrative_boundary_centers_by_province_district_fk FOREIGN KEY (province_code,district_code) REFERENCES administrative.administrative_districts(province_code,district_code) ON DELETE SET NULL ON UPDATE CASCADE,
	CONSTRAINT administrative_boundary_centers_by_province_fk FOREIGN KEY (province_code,osm_id) REFERENCES administrative.administrative_boundaries_by_province(province_code,osm_id) ON DELETE CASCADE
