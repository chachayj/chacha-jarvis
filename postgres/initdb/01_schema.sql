-- 0) 기본 스키마 (선택)
CREATE SCHEMA IF NOT EXISTS administrative;

CREATE TABLE administrative.administrative_countries (
	country_code bpchar(2) NOT NULL,
	country_name text NOT NULL,
	CONSTRAINT countries_pkey PRIMARY KEY (country_code)
);

COMMENT ON TABLE  administrative.administrative_countries IS '국가 코드와 이름 매핑 테이블';
COMMENT ON COLUMN administrative.administrative_countries.country_code IS 'ISO 3166-1 alpha-2 국가 코드';
COMMENT ON COLUMN administrative.administrative_countries.country_name IS '국가 이름';




CREATE TABLE IF NOT EXISTS administrative.administrative_provinces (
  province_code TEXT PRIMARY KEY,                 -- 예: 'KR-SEOUL', 'KR-INCHEON'
  province_name TEXT NOT NULL,                    -- 예: '서울특별시', '인천광역시'
  country_code  CHAR(2) NOT NULL
    REFERENCES administrative.administrative_countries(country_code)
);

COMMENT ON TABLE  administrative.administrative_provinces IS '광역시·도(최상위 지방정부) 식별 코드 및 이름';
COMMENT ON COLUMN administrative.administrative_provinces.province_code IS '광역시·도 식별 코드';
COMMENT ON COLUMN administrative.administrative_provinces.province_name IS '광역시·도 이름';
COMMENT ON COLUMN administrative.administrative_provinces.country_code  IS '소속 국가 코드';





CREATE TABLE IF NOT EXISTS administrative.administrative_level_mapping (
  osm_admin_level   INT PRIMARY KEY,
  iso_un_level_code VARCHAR(10),
  iso_un_level_int  INT,
  description_ko    VARCHAR(100),
  description_en    VARCHAR(100)
);

COMMENT ON TABLE  administrative.administrative_level_mapping IS 'OSM admin_level ↔ 내부 표준 레벨 매핑(한국 기준)';
COMMENT ON COLUMN administrative.administrative_level_mapping.osm_admin_level   IS 'OSM admin_level(정수)';
COMMENT ON COLUMN administrative.administrative_level_mapping.iso_un_level_code IS '내부 표준 레벨 코드(문자)';
COMMENT ON COLUMN administrative.administrative_level_mapping.iso_un_level_int  IS '내부 표준 레벨 코드(숫자)';
COMMENT ON COLUMN administrative.administrative_level_mapping.description_ko    IS '설명(한국어)';
COMMENT ON COLUMN administrative.administrative_level_mapping.description_en    IS '설명(영어)';



CREATE table IF NOT EXISTS  administrative.administrative_boundaries_by_province (
	province_code text NOT NULL,
	id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
	geom public.geometry(multipolygon, 4326) NOT NULL,
	osm_id int8 NOT NULL,
	"name" text NULL,
	name_en text NULL,
	boundary text NULL,
	admin_level int4 NULL,
	country_code bpchar(2) NOT NULL,
	admin_centre_node_id int8 NULL,
	admin_centre_node_lat float8 NULL,
	admin_centre_node_lng float8 NULL,
	label_node_id int8 NULL,
	label_node_lat float8 NULL,
	label_node_lng float8 NULL,
	CONSTRAINT administrative_boundaries_by_province_pkey PRIMARY KEY (province_code, id),
	CONSTRAINT administrative_boundaries_by_province_unique UNIQUE (province_code, osm_id),
	CONSTRAINT administrative_boundaries_by_province_level_fk FOREIGN KEY (admin_level) REFERENCES administrative.administrative_level_mapping(osm_admin_level),
	CONSTRAINT administrative_boundaries_by_province_province_fk FOREIGN KEY (province_code) REFERENCES administrative.administrative_provinces(province_code)
)
PARTITION BY LIST (province_code);


COMMENT ON TABLE  administrative.administrative_boundaries_by_province IS
'광역시·도 단위 LIST 파티셔닝된 OSM 행정경계(멀티폴리곤, EPSG:4326).';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.province_code IS '파티션 키: 광역시·도 식별 코드';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.geom          IS '행정경계 멀티폴리곤(4326)';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.osm_id        IS 'OpenStreetMap 원본 ID';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.name          IS '행정경계 이름(현지어)';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.name_en       IS '행정경계 이름(영문)';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.boundary      IS 'OSM boundary 태그 값';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.admin_level   IS 'OSM admin_level 값';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.country_code  IS '소속 국가 코드';


COMMENT ON COLUMN administrative.administrative_boundaries_by_province.admin_centre_node_id  IS '행정센터 OSM node ID';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.admin_centre_node_lat IS '행정센터 위도';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.admin_centre_node_lng IS '행정센터 경도';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.label_node_id         IS '라벨용 OSM node ID';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.label_node_lat        IS '라벨 표시 위도';
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.label_node_lng        IS '라벨 표시 경도';









