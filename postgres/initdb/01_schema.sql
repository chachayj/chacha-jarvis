CREATE INDEX administrative_boundary_centers_by_province_osm_idx ON administrative.administrative_boundary_centers_by_province USING btree (osm_id);

COMMENT ON TABLE  administrative.administrative_boundary_centers_by_province IS
'광역시·도 파티션 내 행정경계별 대표 좌표(항상 경계 내부의 점; WGS84).';
