  IS '행정중심(청사 등) OSM 노드 ID.';
COMMENT ON COLUMN administrative.administrative_districts.admin_centre_node_lat
  IS '행정중심 위도(WGS84).';
COMMENT ON COLUMN administrative.administrative_districts.admin_centre_node_lng
  IS '행정중심 경도(WGS84).';
