-- 주석
COMMENT ON COLUMN administrative.administrative_boundaries_by_province.district_code
  IS '구 코드 (예: KR-INCHEON-JUNGGU, KR-SEOUL-SEOCHOGU).';

-- 2) FK (선택) : districts 기준으로 정합성 관리 원하면 활성화
--    NULL 허용 컬럼이라 FK가 값 있을 때만 체크됨
ALTER TABLE administrative.administrative_boundaries_by_province
  ADD CONSTRAINT administrative_boundaries_by_province_district_fk
  FOREIGN KEY (province_code, district_code)
  REFERENCES administrative.administrative_districts (province_code, district_code)
  ON UPDATE CASCADE
  ON DELETE SET NULL;

-- 3) 인덱스 (파티션드 인덱스로 생성됨)
CREATE INDEX IF NOT EXISTS abp_province_district_idx
  ON administrative.administrative_boundaries_by_province (province_code, district_code);

-- 4) 기존 데이터 백필
--    현재 인천 파티션 데이터 = 중구, 서울 파티션 데이터 = 서초구 라고 했으니 다음처럼 채움
UPDATE administrative.administrative_boundaries_by_province
SET district_code = 'KR-INCHEON-JUNGGU'
WHERE province_code = 'KR-INCHEON'
  AND (district_code IS NULL OR district_code <> 'KR-INCHEON-JUNGGU');

UPDATE administrative.administrative_boundaries_by_province
SET district_code = 'KR-SEOUL-SEOCHOGU'
WHERE province_code = 'KR-SEOUL'
  AND (district_code IS NULL OR district_code <> 'KR-SEOUL-SEOCHOGU');









    
