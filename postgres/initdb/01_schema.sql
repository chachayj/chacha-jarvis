CREATE TABLE IF NOT EXISTS administrative.administrative_district_centers (
  province_code  text        NOT NULL,
  district_code  text        NOT NULL,
  longitude      float8      NOT NULL,
  latitude       float8      NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT administrative_district_centers_pkey
    PRIMARY KEY (province_code, district_code),
  CONSTRAINT administrative_district_centers_fk
    FOREIGN KEY (province_code, district_code)
    REFERENCES administrative.administrative_districts(province_code, district_code)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT administrative_district_centers_lonlat_chk
    CHECK (longitude BETWEEN -180 AND 180 AND latitude BETWEEN -90 AND 90)
);

-- 조회 최적화(선택) – province 단위로 자주 필터링하면 도움됩니다.
CREATE INDEX IF NOT EXISTS administrative_district_centers_province_idx
  ON administrative.administrative_district_centers (province_code);

    


